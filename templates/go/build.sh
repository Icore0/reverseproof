#!/usr/bin/env bash
# -trimpath removes build paths; -s -w strip symbol + DWARF tables; empty buildid removes a fingerprint.
set -euo pipefail
go build -trimpath -ldflags="-s -w -buildid=" -o "${1:-app}" ./...
